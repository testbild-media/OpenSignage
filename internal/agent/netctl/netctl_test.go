type sys struct {
	t    *testing.T
	root string
	cmds []string
	fail map[string]error // command prefix → error
	out  map[string]string
}

func newSys(t *testing.T, backend string) (*sys, *Helper) {
	t.Helper()
	s := &sys{t: t, root: t.TempDir(), fail: map[string]error{}, out: map[string]string{}}
	for _, n := range []string{"enp2s0", "wlan0"} {
		s.put("/sys/class/net/"+n+"/device/vendor", "0x10ec")
		s.put("/sys/class/net/"+n+"/type", "1\n")
	}
	s.put("/sys/class/net/wlan0/phy80211/rfkill0/soft", "1\n")
	s.put("/etc/resolv.conf", "# Generated by dhcpcd\nnameserver 10.20.0.1\n")
	switch backend {
	case netcfg.BackendIfupdown:
		s.put("/etc/network/interfaces", "source /etc/network/interfaces.d/*\nauto lo\niface lo inet loopback\n\nallow-hotplug enp2s0\niface enp2s0 inet dhcp\n")
		if err := os.MkdirAll(filepath.Join(s.root, "etc/network/interfaces.d"), 0o755); err != nil {
			t.Fatal(err)
		}
	case netcfg.BackendNM:
		s.put("/run/NetworkManager/devices/2", "")
	}
	h := &Helper{Root: s.root, Now: func() time.Time { return time.Date(2026, 10, 19, 12, 0, 0, 0, time.UTC) }, Sleep: func(time.Duration) {},
		Run: func(_ context.Context, _ time.Duration, name string, args ...string) ([]byte, error) {
			cmd := strings.Join(append([]string{name}, args...), " ")
			s.cmds = append(s.cmds, cmd)
			for prefix, err := range s.fail {
				if strings.HasPrefix(cmd, prefix) {
					return nil, err
				}
			}
			for prefix, out := range s.out {
				if strings.HasPrefix(cmd, prefix) {
					return []byte(out), nil
				}
			}
			return nil, nil
		}}
	return s, h
}

func (s *sys) put(p, content string) {
	s.t.Helper()
	full := filepath.Join(s.root, filepath.FromSlash(p))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		s.t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		s.t.Fatal(err)
	}
}

func (s *sys) get(p string) string {
	b, err := os.ReadFile(filepath.Join(s.root, filepath.FromSlash(p)))
	if err != nil {
		return "<missing>"
	}
	return string(b)
}

func (s *sys) ran(cmd string) bool {
	for _, c := range s.cmds {
		if c == cmd {
			return true
		}
	}
	return false
}

// reboot: everything under /run is gone.
func (s *sys) reboot() {
	_ = os.RemoveAll(filepath.Join(s.root, "run"))
}

func static(addr, gw string, dns ...string) netcfg.Config {
	return netcfg.Config{Interface: "enp2s0", Kind: netcfg.KindEthernet, Method: netcfg.MethodStatic, Static: &netcfg.IPv4{Address: addr, Gateway: gw, DNS: dns}}
}

func TestIfupdownApplyConfirm(t *testing.T) {
	s, h := newSys(t, netcfg.BackendIfupdown)
	ctx := context.Background()
	if err := h.Apply(ctx, static("10.20.3.200/22", "10.20.0.1", "1.1.1.1")); err != nil {
		t.Fatal(err)
	}
	// Active until the next reboot: the system files are untouched, the stanza lives in /run.
	if !s.ran("ifdown enp2s0") || !s.ran("ifup -i /run/opensignage-net/interfaces-enp2s0 enp2s0") {
		t.Fatalf("commands: %v", s.cmds)
	}
	if !strings.Contains(s.get("/run/opensignage-net/interfaces-enp2s0"), "iface enp2s0 inet static\n\taddress 10.20.3.200/22\n\tgateway 10.20.0.1\n") {
		t.Fatalf("pending stanza: %s", s.get("/run/opensignage-net/interfaces-enp2s0"))
	}
	if strings.Contains(s.get("/etc/network/interfaces"), "#opensignage#") || s.get("/etc/network/interfaces.d/opensignage-enp2s0") != "<missing>" {
		t.Fatal("system files changed before confirmation")
	}
	if !strings.HasPrefix(s.get("/etc/resolv.conf"), "# OpenSignage begin (static DNS servers)\nnameserver 1.1.1.1\n# OpenSignage end\n# Generated by dhcpcd\n") ||
		!strings.Contains(s.get("/etc/resolv.conf.head"), "nameserver 1.1.1.1") {
		t.Fatalf("dns: %s / %s", s.get("/etc/resolv.conf"), s.get("/etc/resolv.conf.head"))
	}
	p := netcfg.ReadPending(filepath.Join(s.root, "run/opensignage-net/pending.json"))
	if p == nil || strings.Join(p.Interfaces, ",") != "enp2s0" {
		t.Fatalf("pending: %+v", p)
	}

	// A second change before the confirmation goes down with the pending configuration.
	s.cmds = nil
	if err := h.Apply(ctx, static("10.20.3.201/22", "10.20.0.1", "1.1.1.1")); err != nil {
		t.Fatal(err)
	}
	if !s.ran("ifdown -i /run/opensignage-net/interfaces-enp2s0 enp2s0") {
		t.Fatalf("down with the pending file: %v", s.cmds)
	}

	if err := h.Confirm(ctx); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(s.get("/etc/network/interfaces"), "#opensignage# allow-hotplug enp2s0\n#opensignage# iface enp2s0 inet dhcp") {
		t.Fatalf("system stanza not disabled:\n%s", s.get("/etc/network/interfaces"))
	}
	if !strings.Contains(s.get("/etc/network/interfaces.d/opensignage-enp2s0"), "address 10.20.3.201/22") {
		t.Fatal("confirmed stanza")
	}
	if !strings.Contains(s.get("/var/lib/opensignage-net/original/etc_network_interfaces"), "iface enp2s0 inet dhcp") {
		t.Fatal("original saved")
	}
	if s.get("/run/opensignage-net/pending.json") != "<missing>" || s.get("/run/opensignage-net/up-enp2s0") != "<missing>" ||
		s.get("/var/lib/opensignage-net/unconfirmed") != "<missing>" {
		t.Fatal("pending state left")
	}
	if c := netcfg.ReadSummary(filepath.Join(s.root, "etc/opensignage/network/enp2s0.json")); c == nil || c.Static.Address != "10.20.3.201/22" {
		t.Fatalf("summary: %+v", c)
	}
	// After a reboot nothing changes back.
	s.reboot()
	if err := h.Cleanup(); err != nil || !strings.Contains(s.get("/etc/resolv.conf"), "nameserver 1.1.1.1") {
		t.Fatalf("cleanup after confirmation: %v", err)
	}
}

// ifup starts dhcpcd and wpa_supplicant: they must not belong to the agent's service, or
// they stop with it at its next update or restart.
func TestIfupRunsInItsOwnScope(t *testing.T) {
	s, h := newSys(t, netcfg.BackendIfupdown)
	s.put("/run/systemd/system/.booted", "")
	if err := h.Apply(context.Background(), static("10.20.3.200/22", "10.20.0.1")); err != nil {
		t.Fatal(err)
	}
	scoped := "systemd-run --scope --quiet --collect --description=OpenSignage network settings: ifup enp2s0 " + netcfg.Tool("ifup") +
		" -i /run/opensignage-net/interfaces-enp2s0 enp2s0"
	if !s.ran(scoped) || s.ran("ifup -i /run/opensignage-net/interfaces-enp2s0 enp2s0") {
		t.Fatalf("ifup must run in a scope of its own: %v", s.cmds)
	}
}

