func TestValidation(t *testing.T) {
	_, h := newSys(t, netcfg.BackendIfupdown)
	ctx := context.Background()
	for name, c := range map[string]netcfg.Config{
		"unknown iface": {Interface: "eth9", Kind: netcfg.KindEthernet, Method: netcfg.MethodDHCP},
		"wrong kind":    {Interface: "enp2s0", Kind: netcfg.KindWifi, Method: netcfg.MethodDHCP, Wifi: &netcfg.Wifi{SSID: "x", Open: true, Country: "DE"}},
		"bad address":   static("10.0.0.0/8", ""),
	} {
		if err := h.Apply(ctx, c); err == nil {
			t.Errorf("%s accepted", name)
		}
	}
	if _, err := h.Scan(ctx, "enp2s0", ""); err == nil {
		t.Error("scan of a wired interface")
	}
	if err := h.InstallFirmware(ctx, "openssh-server"); err == nil {
		t.Error("any package")
	}
}

func TestNetworkManager(t *testing.T) {
	s, h := newSys(t, netcfg.BackendNM)
	ctx := context.Background()
	if err := h.Apply(ctx, static("10.20.2.215/22", "10.20.0.1", "10.20.0.1")); err != nil {
		t.Fatal(err)
	}
	kf := s.get("/run/NetworkManager/system-connections/opensignage-pending-enp2s0.nmconnection")
	uuid := nmUUID(kf)
	if uuid == "" || !strings.Contains(kf, "address1=10.20.2.215/22,10.20.0.1") || !s.ran("nmcli connection reload") || !s.ran("nmcli --wait 60 connection up uuid "+uuid) {
		t.Fatalf("pending profile: %s %v", kf, s.cmds)
	}
	s.out["nmcli -t -f UUID,TYPE connection show"] = uuid + ":802-3-ethernet\nwired-1:802-3-ethernet\nwifi-1:802-11-wireless\nother-eth:802-3-ethernet\n"
	s.out["nmcli -g connection.interface-name connection show uuid other-eth"] = "eth1\n"
	s.out["nmcli -g connection.interface-name connection show uuid wired-1"] = "enp2s0\n"
	if err := h.Confirm(ctx); err != nil {
		t.Fatal(err)
	}
	if !s.ran("nmcli connection modify uuid "+uuid+" connection.id opensignage-enp2s0") || !s.ran("nmcli connection delete uuid wired-1") ||
		s.ran("nmcli connection delete uuid wifi-1") || s.ran("nmcli connection delete uuid other-eth") || s.ran("nmcli connection delete uuid "+uuid) {
		t.Fatalf("confirm: %v", s.cmds)
	}
	// Wireless network: country kept with raspi-config on Raspberry Pi OS.
	s.put("/usr/bin/raspi-config", "")
	w := netcfg.Config{Interface: "wlan0", Kind: netcfg.KindWifi, Method: netcfg.MethodDHCP, Wifi: &netcfg.Wifi{SSID: "Bar", Passphrase: "secret123", Country: "AT"}}
	if err := h.Apply(ctx, w); err != nil {
		t.Fatal(err)
	}
	if err := h.Confirm(ctx); err != nil {
		t.Fatal(err)
	}
	if !s.ran("raspi-config nonint do_wifi_country AT") {
		t.Fatalf("country: %v", s.cmds)
	}
	s.out["nmcli -t -f SSID,SIGNAL,SECURITY,FREQ device wifi list ifname wlan0 --rescan yes"] = "Bar:80:WPA2:2412 MHz\n"
	// Raspberry Pi OS keeps NetworkManager's Wi-Fi switched off: switched on before the scan.
	s.out["nmcli radio wifi"] = "disabled\n"
	s.out["nmcli -t -f DEVICE,STATE device"] = "eth0:connected\nwlan0:disconnected\n"
	s.cmds = nil
	aps, err := h.Scan(ctx, "wlan0", "AT")
	if err != nil || len(aps) != 1 || aps[0].SSID != "Bar" {
		t.Fatalf("scan: %v %+v", err, aps)
	}
	if !s.ran("nmcli radio wifi on") || s.get("/sys/class/net/wlan0/phy80211/rfkill0/soft") != "0" {
		t.Fatalf("radio not switched on: %v", s.cmds)
	}
	// The radio rules of the country come first (5 GHz networks need them).
	if !s.ran("iw reg set AT") {
		t.Fatalf("country not set before the scan: %v", s.cmds)
	}
	s.cmds = nil
	if _, err := h.Scan(ctx, "wlan0", "../x"); err != nil || s.ran("iw reg set ../x") {
		t.Fatalf("an invalid country is ignored: %v %v", err, s.cmds)
	}
}

func TestFirmware(t *testing.T) {
	s, h := newSys(t, netcfg.BackendIfupdown)
	s.out["dmesg"] = "usb 1-2: Direct firmware load for rtw88/rtw8822b_fw.bin failed with error -2\nDirect firmware load for i915/x.bin failed\n"
	hints, err := h.Firmware(context.Background())
	if err != nil || len(hints) != 1 || hints[0].Package != "firmware-realtek" {
		t.Fatalf("hints: %v %+v", err, hints)
	}
	s.put("/lib/firmware/rtw88/rtw8822b_fw.bin", "x")
	if hints, _ := h.Firmware(context.Background()); len(hints) != 0 {
		t.Fatal("installed meanwhile")
	}
	if err := h.InstallFirmware(context.Background(), "firmware-realtek"); err != nil || !s.ran("apt-get install -y -q --no-install-recommends firmware-realtek") {
		t.Fatalf("install: %v %v", err, s.cmds)
	}
}
